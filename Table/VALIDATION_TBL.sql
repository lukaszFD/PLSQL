CREATE TABLE VALIDATION_LOG (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    HASH_ID           VARCHAR2(128) NOT NULL,              -- Unique hash per validation
    ITEM_TYPE         VARCHAR2(10) NOT NULL,               -- 
    ITEM_ID           VARCHAR2(64) NOT NULL,               -- Identifier
    VALIDATION_STATUS VARCHAR2(20) NOT NULL,               -- VALIDATED, FAILED, etc.
    VALIDATION_DATE   TIMESTAMP DEFAULT SYSTIMESTAMP,      -- Validation date and time
    VALIDATED_BY      VARCHAR2(64),                        -- User/system who validated
    COMMENTS          VARCHAR2(4000),                      -- Optional comments
    SOURCE_SYSTEM     VARCHAR2(64),                        -- E.g., ServiceNow
    JSON_DATA         CLOB CHECK (JSON_DATA IS JSON),      -- JSON content (validated)
    
    CONSTRAINT uq_hash_id UNIQUE (HASH_ID)
);